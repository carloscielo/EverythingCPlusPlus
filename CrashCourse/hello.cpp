// iostream is a C++ Standard Library header file that provides input/output functionality
// io = Input/Output, stream = flow of data
// It provides: std::cout (console output), std::cin (input), std::cerr (errors), std::clog (logging)
#include <iostream>

// main() is the entry point of every C++ program - execution starts here
int main() {
    // std::cout sends data to the console (screen)
    // << is the insertion operator that puts data into the output stream
    // std::endl ends the line and flushes the buffer (like pressing Enter)
    std::cout << "Hello, World!" << std::endl;
    // return 0 indicates the program executed successfully
    return 0;

}
